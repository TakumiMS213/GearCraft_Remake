using System;
using System.Threading;
using Cysharp.Threading.Tasks;
using UnityEngine;

public class EnemySpawner : MonoBehaviour
{
    [Header("Auto Generation")]
    public StageGeneratorSO stageConfig;

    [Serializable]
    public class SpawnGroup
    {
        public EnemyWaveData waveData;
        public float delay;
    }

    [Serializable]
    public class Stage
    {
        public SpawnGroup[] groups;
        public bool loop;
    }

    public Stage[] stages;

    [Header("Options")]
    public bool autoStart = true;
    public bool useAutoGeneration = true;
    public GameObject warning;

    private CancellationTokenSource cts;
    private StageSpawnPlanner spawnPlanner;

    private void Start()
    {
        spawnPlanner = new StageSpawnPlanner(stageConfig);

        int startStage = StageCounter.Instance != null ? StageCounter.Instance.StageCount : 1;
        if (autoStart)
        {
            StartStage(startStage);
        }
    }

    public void StartStage(int stageIndex)
    {
        StopSpawning();
        cts = new CancellationTokenSource();
        spawnPlanner = new StageSpawnPlanner(stageConfig);

        if (useAutoGeneration && stageConfig != null)
        {
            SpawnAutoGeneratedStage(stageIndex, cts.Token).Forget();
        }
        else if (stages != null && stageIndex >= 0 && stageIndex < stages.Length)
        {
            SpawnStageAsync(stages[stageIndex], cts.Token).Forget();
        }
    }

    public void StopSpawning()
    {
        if (cts == null)
        {
            return;
        }

        if (!cts.IsCancellationRequested)
        {
            cts.Cancel();
        }

        cts.Dispose();
        cts = null;
    }

    private async UniTaskVoid SpawnAutoGeneratedStage(int stageNum, CancellationToken token)
    {
        try
        {
            if (stageConfig.IsBossStage(stageNum) && warning != null)
            {
                warning.SetActive(true);
            }

            if (stageConfig.IsBossStage(stageNum))
            {
                await SpawnBossStage(stageNum, token);
            }
            else
            {
                await SpawnNormalStage(stageNum, token);
            }
        }
        catch (OperationCanceledException)
        {
        }
    }

    private async UniTask SpawnNormalStage(int stageNum, CancellationToken token)
    {
        int enemyCount = stageConfig.GetEnemyCount(stageNum);
        float spawnInterval = stageConfig.GetSpawnInterval(stageNum);
        float difficulty = stageConfig.GetDifficulty(stageNum);

        if (stageConfig.normalEnemyPool == null || stageConfig.normalEnemyPool.Length == 0)
        {
            Debug.LogError("normalEnemyPool is empty.");
            return;
        }

        for (int i = 0; i < enemyCount; i++)
        {
            token.ThrowIfCancellationRequested();

            EnemyDataSO selectedEnemy = SelectEnemyByDifficulty(stageNum, difficulty);
            if (selectedEnemy == null || selectedEnemy.prefab == null)
            {
                continue;
            }

            GameObject spawned = Instantiate(selectedEnemy.prefab, transform.position, Quaternion.identity);
            EnemyController enemy = spawned.GetComponent<EnemyController>();
            if (enemy != null)
            {
                enemy.enemyData = selectedEnemy;
                enemy.isLastEnemy = i == enemyCount - 1;
            }

            await UniTask.Delay((int)(spawnInterval * 1000f), cancellationToken: token);
        }
    }

    private async UniTask SpawnBossStage(int stageNum, CancellationToken token)
    {
        StageSpawnPlan plan = spawnPlanner.CreatePlan(stageNum);
        float spawnInterval = stageConfig.GetSpawnInterval(stageNum);
        float difficulty = stageConfig.GetDifficulty(stageNum);

        if (stageConfig.normalEnemyPool != null && stageConfig.normalEnemyPool.Length > 0)
        {
            for (int i = 0; i < plan.MinionCount; i++)
            {
                token.ThrowIfCancellationRequested();
                EnemyDataSO minionData = SelectEnemyByDifficulty(stageNum, difficulty);
                if (minionData == null || minionData.prefab == null)
                {
                    continue;
                }

                GameObject spawned = Instantiate(minionData.prefab, transform.position, Quaternion.identity);
                EnemyController enemy = spawned.GetComponent<EnemyController>();
                if (enemy != null)
                {
                    enemy.enemyData = minionData;
                    enemy.isLastEnemy = plan.MarkLastMinionAsStageEnd && i == plan.MinionCount - 1;
                }

                await UniTask.Delay((int)(spawnInterval * 1000f), cancellationToken: token);
            }
        }

        if (!plan.HasBoss)
        {
            Debug.LogWarning($"Boss data is missing for stage {stageNum}. The last minion will end the stage.");
            return;
        }

        token.ThrowIfCancellationRequested();
        EnemyDataSO bossData = plan.BossData;

        await UniTask.Delay(2000, cancellationToken: token);

        GameObject bossObject = Instantiate(bossData.prefab, transform.position, Quaternion.identity);
        EnemyController bossEnemy = bossObject.GetComponent<EnemyController>();
        if (bossEnemy != null)
        {
            bossEnemy.enemyData = bossData;
            bossEnemy.isLastEnemy = true;
        }
    }

    private int GetAvailablePoolMax(int stageNum)
    {
        EnemyDataSO[] pool = stageConfig.normalEnemyPool;
        if (pool == null || pool.Length == 0)
        {
            return 0;
        }

        if (stageNum <= 1)
        {
            return 1;
        }

        int bossKillCount = StatusManager.Instance != null ? StatusManager.Instance.bossKillCount : 0;
        if (bossKillCount <= 0)
        {
            return Mathf.Min(3, pool.Length);
        }

        if (bossKillCount == 1)
        {
            return Mathf.Min(6, pool.Length);
        }

        return pool.Length;
    }

    private EnemyDataSO SelectEnemyByDifficulty(int stageNum, float difficulty)
    {
        EnemyDataSO[] pool = stageConfig.normalEnemyPool;
        if (pool == null || pool.Length == 0)
        {
            return null;
        }

        int availableMax = Mathf.Max(1, GetAvailablePoolMax(stageNum));
        float biasedIndex = difficulty * (availableMax - 1) + UnityEngine.Random.Range(-1f, 1f);
        int index = Mathf.Clamp(Mathf.RoundToInt(biasedIndex), 0, availableMax - 1);
        return pool[index];
    }

    private async UniTaskVoid SpawnStageAsync(Stage stage, CancellationToken token)
    {
        if (stage == null || stage.groups == null)
        {
            return;
        }

        try
        {
            do
            {
                for (int i = 0; i < stage.groups.Length; i++)
                {
                    SpawnGroup group = stage.groups[i];
                    token.ThrowIfCancellationRequested();
                    if (group == null || group.waveData == null)
                    {
                        continue;
                    }

                    await UniTask.Delay((int)(group.delay * 1000f), cancellationToken: token);
                    token.ThrowIfCancellationRequested();
                    await SpawnWaveAsync(group.waveData, token);
                }

                if (stage.loop)
                {
                    await UniTask.Delay(1000, cancellationToken: token);
                }
            }
            while (stage.loop && !token.IsCancellationRequested);
        }
        catch (OperationCanceledException)
        {
        }
    }

    private async UniTask SpawnWaveAsync(EnemyWaveData wave, CancellationToken token)
    {
        float startTime = Time.time;

        for (int i = 0; i < wave.spawns.Length; i++)
        {
            EnemyWaveData.SpawnData data = wave.spawns[i];
            token.ThrowIfCancellationRequested();
            if (data == null || data.enemyPrefab == null)
            {
                continue;
            }

            float wait = Mathf.Max(0f, data.spawnTime - (Time.time - startTime));
            if (wait > 0f)
            {
                await UniTask.Delay((int)(wait * 1000f), cancellationToken: token);
            }

            token.ThrowIfCancellationRequested();
            GameObject spawned = Instantiate(data.enemyPrefab, transform.position, Quaternion.identity);
            EnemyController enemy = spawned.GetComponent<EnemyController>();
            if (enemy != null)
            {
                enemy.SetWaveData(data);
            }
        }
    }
}
